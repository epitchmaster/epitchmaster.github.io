  function fromEspn(ev) {
    var c = (ev.competitions || [])[0] || {};
    var lid = ((c.uid || ev.uid || "").match(/~l:(\d+)/) || [])[1] || "";
    var lg = lgInfo(lid, ev);
    var side = {};
    (c.competitors || []).forEach(function (t) {
      var tm = t.team || {};
      side[t.homeAway] = { id: tm.id, name: tm.displayName || tm.name || "?", short: tm.shortDisplayName || tm.displayName || "?",
        logo: espnImg(tm.logo, 48), score: t.score, so: t.shootoutScore, win: t.winner };
    });
    var st = ev.status || c.status || {}, ty = st.type || {};
    return { id: ev.id, src: "espn", lg: lg, t: new Date(ev.date), home: side.home || { name: "?" }, away: side.away || { name: "?" },
      st: statusOf(ty.name, ty.state, st.displayClock), det: evDetails(c), hasDet: !!(c.details && c.details.length) };
  }
  function fromTsdb(e, L) {
    var ts = e.strTimestamp ? new Date(e.strTimestamp.replace(" ", "T") + (/[zZ+]/.test(e.strTimestamp.slice(10)) ? "" : "Z")) : new Date(e.dateEvent + "T" + (e.strTime || "00:00:00") + "Z");
    var tiny = function (u) { return u ? u + "/tiny" : ""; };
    return { id: "ts" + e.idEvent, src: "tsdb", lg: { key: L.key, en: L.name, logo: L.logo || tiny(e.strLeagueBadge) }, t: ts,
      home: { name: e.strHomeTeam, short: e.strHomeTeam, logo: tiny(e.strHomeTeamBadge), score: e.intHomeScore },
      away: { name: e.strAwayTeam, short: e.strAwayTeam, logo: tiny(e.strAwayTeamBadge), score: e.intAwayScore },
      st: e.strPostponed === "yes" ? { k: "off", label: "เลื่อน" } : tsdbStatus(e.strStatus, e.intHomeScore), det: [], hasDet: false, noDet: true };
  }

  /* ---------- fetching (cache per source-day) ---------- */
  var cache = {};   /* key -> {at, events, err} */
  function getEspnDay(yyyymmdd, force) {
    var k = "e" + yyyymmdd, c = cache[k];
    if (c && !force && c.events) return Promise.resolve(c);
    return fetchJSON(ESPN + "all/scoreboard?dates=" + yyyymmdd + "&limit=1000", 20000).then(function (j) {
      cache[k] = { at: Date.now(), events: (j.events || []).map(fromEspn) }; return cache[k];
    }, function (err) { if (c && c.events) return c; throw err; });
  }
  function getTsdbDay(ymd, force) {
    var k = "t" + ymd, c = cache[k];
    if (c && !force && c.events) return Promise.resolve(c);
    /* free key: eventsday is capped (≈3 rows) so also merge last/next round results */
    var jobs = [];
    TSDB_LEAGUES.forEach(function (L) {
      jobs.push(fetchJSON(TSDB + "eventsday.php?d=" + ymd + "&l=" + L.id, 12000).then(function (j) { return { L: L, ev: j.events || [] }; }, function () { return { L: L, ev: [], fail: 1 }; }));
    });
    jobs.push(fetchJSON(TSDB + "eventspastleague.php?id=4743", 12000).then(function (j) { return { L: TSDB_LEAGUES[0], ev: j.events || [] }; }, function () { return { L: TSDB_LEAGUES[0], ev: [] }; }));
    jobs.push(fetchJSON(TSDB + "eventsnextleague.php?id=4743", 12000).then(function (j) { return { L: TSDB_LEAGUES[0], ev: j.events || [] }; }, function () { return { L: TSDB_LEAGUES[0], ev: [] }; }));
    return Promise.all(jobs).then(function (rs) {
      var seen = {}, out = [], fails = 0;
      rs.forEach(function (r) {
        if (r.fail) fails++;
        r.ev.forEach(function (e) { if (e.strSport && e.strSport !== "Soccer") return; if (seen[e.idEvent]) return; seen[e.idEvent] = 1; out.push(fromTsdb(e, r.L)); });
      });
      if (fails === TSDB_LEAGUES.length && !out.length) throw new Error("TheSportsDB unavailable");
      cache[k] = { at: Date.now(), events: out }; return cache[k];
    });
  }

