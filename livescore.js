  function load(force) {
    var day = S.day, e1 = compact(addDays(day, -1)), e2 = compact(day);
    S.loading = true; S.err = ""; if (!S.events.length || force === "day") render();
    var espnJobs = [getEspnDay(e1, force === true), getEspnDay(e2, force === true)];
    var tsJob = getTsdbDay(day, force === true).then(function (c) { return c; }, function () { return { events: [], failed: true }; });
    return Promise.all([Promise.all(espnJobs).then(function (r) { return r; }, function (err) { return { error: err }; }), tsJob]).then(function (res) {
      if (day !== S.day) return;
      var espn = res[0], ts = res[1], all = [];
      S.loading = false; S.warn = "";
      if (espn.error) { S.err = "โหลดข้อมูลจาก ESPN ไม่สำเร็จ (" + (espn.error.name === "AbortError" ? "หมดเวลา" : esc(espn.error.message || "เครือข่าย")) + ")"; }
      else espn.forEach(function (c) { all = all.concat(c.events); });
      if (ts.failed) S.warn = "โหลดไทยลีกจาก TheSportsDB ไม่สำเร็จ";
      all = all.concat(ts.events || []);
      var seen = {};
      S.events = all.filter(function (m) { if (seen[m.id]) return false; seen[m.id] = 1; return bkkDay(m.t) === day; });
      S.updated = new Date();
      render(); schedule();
    });
  }
  function hasLiveOrSoon() {
    var now = Date.now();
    return S.events.some(function (m) { return m.st.k === "live" || m.st.k === "break" || (m.st.k === "pre" && m.t.getTime() - now < 10 * 60000 && now - m.t.getTime() < 3 * 3600000); });
  }
  function schedule() {
    clearTimeout(timer); timer = null;
    if (document.visibilityState !== "visible" || !hasLiveOrSoon()) return;
    timer = setTimeout(function () { load(true); }, REFRESH_MS);
  }
  document.addEventListener("visibilitychange", function () {
    if (!started) return;
    if (document.visibilityState === "visible") { if (S.updated && Date.now() - S.updated > REFRESH_MS && hasLiveOrSoon()) load(true); else schedule(); }
    else { clearTimeout(timer); timer = null; }
  });

