  /* returns {k: live|break|post|pre|off, label, clock} */
  function statusOf(name, state, clock) {
    if (LIVE_NAMES[name]) return { k: "live", label: LIVE_NAMES[name], clock: clock || "" };
    if (BREAK_NAMES[name]) return { k: "break", label: BREAK_NAMES[name], clock: "" };
    if (POST_NAMES[name]) return { k: "post", label: POST_NAMES[name] };
    if (OFF_NAMES[name]) return { k: "off", label: OFF_NAMES[name] };
    if (state === "in") return { k: "live", label: "กำลังแข่ง", clock: clock || "" };
    if (state === "post") return { k: "post", label: "จบเกม" };
    return { k: "pre", label: "ยังไม่เตะ" };
  }
  function tsdbStatus(s, hs) {
    s = (s || "").toUpperCase();
    if (s === "1H") return { k: "live", label: "ครึ่งแรก", clock: "" };
    if (s === "2H") return { k: "live", label: "ครึ่งหลัง", clock: "" };
    if (s === "ET" || s === "P" || s === "LIVE" || s === "BT") return { k: "live", label: "กำลังแข่ง", clock: "" };
    if (s === "HT") return { k: "break", label: "พักครึ่ง" };
    if (s === "FT" || s === "MATCH FINISHED") return { k: "post", label: "จบเกม" };
    if (s === "AET") return { k: "post", label: "จบเกม (ต่อเวลา)" };
    if (s === "PEN") return { k: "post", label: "จบเกม (จุดโทษ)" };
    if (s === "PST" || s === "POSTPONED") return { k: "off", label: "เลื่อน" };
    if (s === "CANC" || s === "CANCELLED") return { k: "off", label: "ยกเลิก" };
    if (s === "ABD" || s === "ABANDONED") return { k: "off", label: "ยุติการแข่งขัน" };
    if (hs != null && hs !== "" && s !== "NS") return { k: "post", label: "จบเกม" };
    return { k: "pre", label: "ยังไม่เตะ" };
  }

